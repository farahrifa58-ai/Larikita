    fun get(key: String, langCode: String): String {
        // Try requested language
        translations[langCode]?.get(key)?.let { return it }
        // Try prefix if langCode has region (e.g. en_GB -> en)
        if (langCode.contains("_")) {
            val baseCode = langCode.substringBefore("_")
            translations[baseCode]?.get(key)?.let { return it }
        }
        // Fallback to English
        translations["en"]?.get(key)?.let { return it }
        // Fallback to Indonesian
        translations["id"]?.get(key)?.let { return it }
        return key
    }
